def md_table(data):
    def escape(value):
        return str(value).replace("|", " · ", 1) if "|" in str(value) else str(value)
    def row(values):
        return "| " + " | ".join(escape(value) for value in values) + " |"
    return "\n".join([row(data["head"]), row(["---"] * len(data["head"])),
                      *(row(values) for values in data["rows"])])


def md_shots(item):
    return ["- [" + shot["cap"] + "](screens/devices-2026-11-09/" + shot["file"] + ")" for shot in item["shots"]]


